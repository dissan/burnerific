def dump(obj: dict, path: Path) -> None:
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    (ROOT / "translations").mkdir(exist_ok=True)
    en = build("en")
    dump(en, ROOT / "strings.json")
    for lang in LANGS:
        dump(build(lang), ROOT / "translations" / f"{lang}.json")

    sys.path.insert(0, str(ROOT))
    from nbe.states import STATE_OPTIONS, SUBSTATE_OPTIONS  # noqa: PLC0415

    missing = [k for k in STATE_OPTIONS if k not in STATES] + [k for k in SUBSTATE_OPTIONS if k not in SUBSTATES]
    if missing:
        raise SystemExit(f"untranslated states: {missing}")
    print("wrote", ", ".join(LANGS))


if __name__ == "__main__":
    main()
